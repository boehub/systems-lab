"""Code generator: syntax tree -> CHIP-8 assembly text.

Register plan (CHIP-8 has sixteen one-byte registers):

    V0..VB   your variables first, then temporaries for evaluating expressions
    VC, VD   the text cursor (y, x) used by print / at / newline
    VE       scratch used by print
    VF       the flag register that CHIP-8 arithmetic overwrites

Every expression is evaluated into a chosen target register. Operands that
need a temporary borrow one from the registers above the variables and give it
back when done; running out is reported as an error instead of miscompiling.
"""

from . import tree
from .check import fold
from .errors import NibbleError

USER_REGS = 12          # V0..VB
CURSOR_Y, CURSOR_X, SCRATCH = 0xC, 0xD, 0xE


def reg(n):
    return f"V{n:X}"


def generate(program, variables):
    return _CodeGen(variables).run(program)


class _CodeGen:
    def __init__(self, variables):
        if len(variables) > USER_REGS:
            raise NibbleError(
                f"too many variables: {len(variables)} (the limit is {USER_REGS}; "
                "CHIP-8 has 16 registers and the compiler keeps 4 for itself)"
            )
        self.regs = {name: i for i, name in enumerate(variables)}
        self.next_temp = len(variables)
        self.lines = []
        self.labels = 0
        self.uses_print = False
        self.line_for_errors = None

    # ---- output helpers ----------------------------------------------------

    def emit(self, text):
        self.lines.append("        " + text)

    def label(self, name):
        self.lines.append(f"{name}:")

    def new_label(self, hint):
        self.labels += 1
        return f"_{hint}{self.labels}"

    def alloc(self, node):
        if self.next_temp >= USER_REGS:
            raise NibbleError(
                "this expression needs more registers than are free "
                "(use fewer variables or split it into steps)",
                node.line,
                node.col,
            )
        r = self.next_temp
        self.next_temp += 1
        return r

    def free(self, r):
        assert r == self.next_temp - 1, "temporaries are released in reverse order"
        self.next_temp -= 1

    # ---- program -----------------------------------------------------------

    def run(self, program):
        self.lines.append("; generated by nibc: do not edit")
        self.emit(f"LD   {reg(CURSOR_X)}, 0          ; text cursor starts top-left")
        self.emit(f"LD   {reg(CURSOR_Y)}, 0")
        self.statements(program.statements)
        self.label("_end")
        self.emit("JP   _end                ; done: spin here")
        if self.uses_print:
            self.print_routine()
        return "\n".join(self.lines) + "\n"

    def statements(self, body):
        for s in body:
            self.statement(s)

    # ---- statements --------------------------------------------------------

    def statement(self, s):
        if isinstance(s, tree.Assign):
            self.assign(s)
        elif isinstance(s, tree.If):
            self.if_statement(s)
        elif isinstance(s, tree.While):
            self.while_statement(s)
        elif isinstance(s, tree.CallStmt):
            self.call_statement(s)
        else:  # pragma: no cover
            raise AssertionError(s)

    def assign(self, s):
        target = self.regs[s.name]
        value = fold(s.value)
        self.lines.append(f"        ; {s.name} = ...")
        if _clobbers(value, s.name):
            tmp = self.alloc(s)
            self.expr(value, tmp)
            self.emit(f"LD   {reg(target)}, {reg(tmp)}")
            self.free(tmp)
        else:
            self.expr(value, target)

    def condition_jump_if_false(self, cond, label, node):
        r = self.alloc(node)
        self.expr(fold(cond), r)
        self.emit(f"SNE  {reg(r)}, 0")
        self.emit(f"JP   {label}")
        self.free(r)

    def if_statement(self, s):
        end = self.new_label("endif")
        if s.otherwise is None:
            self.condition_jump_if_false(s.cond, end, s)
            self.statements(s.then)
            self.label(end)
        else:
            other = self.new_label("else")
            self.condition_jump_if_false(s.cond, other, s)
            self.statements(s.then)
            self.emit(f"JP   {end}")
            self.label(other)
            self.statements(s.otherwise)
            self.label(end)

    def while_statement(self, s):
        top, end = self.new_label("while"), self.new_label("endwhile")
        self.label(top)
        self.condition_jump_if_false(s.cond, end, s)
        self.statements(s.body)
        self.emit(f"JP   {top}")
        self.label(end)

    def call_statement(self, s):
        name = s.name
        if name == "print":
            self.uses_print = True
            self.expr(fold(s.args[0]), SCRATCH)
            self.emit("CALL _print")
        elif name == "newline":
            self.emit(f"LD   {reg(CURSOR_X)}, 0")
            self.emit(f"ADD  {reg(CURSOR_Y)}, 6")
        elif name == "clear":
            self.emit("CLS")
            self.emit(f"LD   {reg(CURSOR_X)}, 0")
            self.emit(f"LD   {reg(CURSOR_Y)}, 0")
        elif name == "at":
            self.expr(fold(s.args[0]), CURSOR_X)
            self.expr(fold(s.args[1]), CURSOR_Y)
        elif name == "wait":
            r = self.alloc(s)
            self.expr(fold(s.args[0]), r)
            self.emit(f"LD   DT, {reg(r)}")
            loop = self.new_label("wait")
            self.label(loop)
            self.emit(f"LD   {reg(r)}, DT")
            self.emit(f"SE   {reg(r)}, 0")
            self.emit(f"JP   {loop}")
            self.free(r)
        else:  # pragma: no cover
            raise AssertionError(name)

    # ---- expressions -------------------------------------------------------

    def expr(self, e, t):
        """Generate code that leaves the value of `e` in register `t`."""
        T = reg(t)
        if isinstance(e, tree.Num):
            self.emit(f"LD   {T}, {e.value}")
        elif isinstance(e, tree.Var):
            r = self.regs[e.name]
            if r != t:
                self.emit(f"LD   {T}, {reg(r)}")
        elif isinstance(e, tree.Unary):
            self.expr(e.operand, t)
            yes, end = self.new_label("not"), self.new_label("endnot")
            self.emit(f"SE   {T}, 0")
            self.emit(f"JP   {yes}")
            self.emit(f"LD   {T}, 1")
            self.emit(f"JP   {end}")
            self.label(yes)
            self.emit(f"LD   {T}, 0")
            self.label(end)
        elif isinstance(e, tree.Call):
            self.call_expr(e, t)
        elif isinstance(e, tree.Binary):
            self.binary(e, t)
        else:  # pragma: no cover
            raise AssertionError(e)

    def call_expr(self, e, t):
        T = reg(t)
        if e.name == "key":
            self.emit(f"LD   {T}, K")
        elif e.name == "rand":
            self.emit(f"RND  {T}, 0xFF")
        elif e.name == "pressed":
            self.expr(e.args[0], t)
            no, end = self.new_label("up"), self.new_label("endkey")
            self.emit(f"SKP  {T}")
            self.emit(f"JP   {no}")
            self.emit(f"LD   {T}, 1")
            self.emit(f"JP   {end}")
            self.label(no)
            self.emit(f"LD   {T}, 0")
            self.label(end)

    def operand(self, e, t, writable):
        """A register holding `e`: a variable's own register when that is safe,
        otherwise a fresh temporary. Returns (register, temporary-or-None)."""
        if isinstance(e, tree.Var) and not writable:
            r = self.regs[e.name]
            if r != t:
                return r, None
        tmp = self.alloc(e)
        self.expr(e, tmp)
        return tmp, tmp

    def binary(self, e, t):
        T, op = reg(t), e.op
        if op in ("and", "or"):
            return self.logic(e, t)

        self.expr(e.left, t)

        if op in ("+", "-") and isinstance(e.right, tree.Num):
            k = e.right.value if op == "+" else (-e.right.value) & 0xFF
            if k:
                self.emit(f"ADD  {T}, {k}")
            return

        if op == "*":
            return self.multiply(e, t)

        # comparisons that swap roles (a > b is b < a) modify the right operand
        writable = op in (">", "<=")
        r, tmp = self.operand(e.right, t, writable)
        R = reg(r)
        if op == "+":
            self.emit(f"ADD  {T}, {R}")
        elif op == "-":
            self.emit(f"SUB  {T}, {R}")
        elif op in ("&", "|", "^"):
            self.emit(f"{ {'&': 'AND', '|': 'OR', '^': 'XOR'}[op] }  {T}, {R}")
        elif op in ("==", "!="):
            # t ^ r is zero exactly when they are equal
            self.emit(f"XOR  {T}, {R}")
            scratch = self.alloc(e) if tmp is None else tmp
            self.emit(f"LD   {reg(scratch)}, {1 if op == '==' else 0}")
            self.emit(f"SE   {T}, 0")
            self.emit(f"LD   {reg(scratch)}, {0 if op == '==' else 1}")
            self.emit(f"LD   {T}, {reg(scratch)}")
            if tmp is None:
                self.free(scratch)
        else:
            # SUB leaves VF = 1 when there was no borrow, i.e. when x >= y.
            if op in ("<", ">="):          # a >= b: VF after a - b
                self.emit(f"SUB  {T}, {R}")
            else:                          # a <= b: VF after b - a;  a > b is its opposite
                self.emit(f"SUB  {R}, {T}")
            self.emit(f"LD   {T}, VF")
            if op in ("<", ">"):           # flip the flag
                if tmp is None:
                    spare = self.alloc(e)
                    self.emit(f"LD   {reg(spare)}, 1")
                    self.emit(f"XOR  {T}, {reg(spare)}")
                    self.free(spare)
                else:
                    self.emit(f"LD   {R}, 1")
                    self.emit(f"XOR  {T}, {R}")
        if tmp is not None:
            self.free(tmp)

    def multiply(self, e, t):
        """t = t * right, by adding t to an accumulator `right` times."""
        T = reg(t)
        count = self.alloc(e)
        self.expr(e.right, count)
        acc = self.alloc(e)
        top, end = self.new_label("mul"), self.new_label("endmul")
        self.emit(f"LD   {reg(acc)}, 0")
        self.label(top)
        self.emit(f"SNE  {reg(count)}, 0")
        self.emit(f"JP   {end}")
        self.emit(f"ADD  {reg(acc)}, {T}")
        self.emit(f"ADD  {reg(count)}, 0xFF")
        self.emit(f"JP   {top}")
        self.label(end)
        self.emit(f"LD   {T}, {reg(acc)}")
        self.free(acc)
        self.free(count)

    def logic(self, e, t):
        """and / or, stopping early once the answer is known. Result is 0 or 1."""
        T = reg(t)
        end = self.new_label("endlogic")
        self.expr(e.left, t)
        if e.op == "and":
            self.emit(f"SNE  {T}, 0")
            self.emit(f"JP   {end}")          # left is 0: the answer is 0
            self.expr(e.right, t)
            self.emit(f"SNE  {T}, 0")
            self.emit(f"JP   {end}")
            self.emit(f"LD   {T}, 1")
        else:
            true = self.new_label("true")
            self.emit(f"SE   {T}, 0")
            self.emit(f"JP   {true}")          # left is nonzero: the answer is 1
            self.expr(e.right, t)
            self.emit(f"SNE  {T}, 0")
            self.emit(f"JP   {end}")
            self.label(true)
            self.emit(f"LD   {T}, 1")
        self.label(end)

    # ---- the print subroutine ---------------------------------------------

    def print_routine(self):
        out = self.lines.append
        out("")
        out("; _print: draw VE (0-255) in decimal at the cursor, no leading zeros.")
        out("; Borrows V0-V2 and puts them back before returning.")
        out("_print:")
        for text in (
            "LD   I, _spill",
            "LD   [I], V2            ; save V0-V2",
            "LD   I, _digits",
            "LD   B, VE",
            "LD   V2, [I]            ; V0 = hundreds, V1 = tens, V2 = ones",
            "LD   VE, 0              ; VE = 1 once a digit has been drawn",
            "SNE  V0, 0",
            "JP   _p_tens             ; no hundreds digit",
            "LD   F, V0",
            "DRW  VD, VC, 5",
            "ADD  VD, 5",
            "LD   VE, 1",
        ):
            self.emit(text)
        self.label("_p_tens")
        for text in (
            "SNE  VE, 1",
            "JP   _p_draw_t           ; a digit was drawn: always draw the tens",
            "SE   V1, 0",
            "JP   _p_draw_t           ; tens digit is nonzero",
            "JP   _p_ones",
        ):
            self.emit(text)
        self.label("_p_draw_t")
        for text in ("LD   F, V1", "DRW  VD, VC, 5", "ADD  VD, 5"):
            self.emit(text)
        self.label("_p_ones")
        for text in (
            "LD   F, V2",
            "DRW  VD, VC, 5",
            "ADD  VD, 5",
            "ADD  VD, 5              ; a space after the number",
            "LD   I, _spill",
            "LD   V2, [I]            ; restore V0-V2",
            "RET",
        ):
            self.emit(text)
        out("_digits: DB 0, 0, 0")
        out("_spill:  DB 0, 0, 0")


def _mentions(e, name):
    if isinstance(e, tree.Var):
        return e.name == name
    if isinstance(e, tree.Binary):
        return _mentions(e.left, name) or _mentions(e.right, name)
    if isinstance(e, tree.Unary):
        return _mentions(e.operand, name)
    if isinstance(e, tree.Call):
        return any(_mentions(a, name) for a in e.args)
    return False


def _clobbers(e, name):
    """True if evaluating `e` straight into variable `name` would overwrite it
    before the expression has finished reading it. Evaluating into the variable
    is fine when it only appears as the leftmost value (x = x + y * 2)."""
    if not _mentions(e, name):
        return False
    if isinstance(e, tree.Var):
        return False
    if isinstance(e, tree.Binary):
        return _mentions(e.right, name) or _clobbers(e.left, name)
    return True
