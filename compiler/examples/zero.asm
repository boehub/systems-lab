; Draws the CHIP-8 "0" glyph in the top-left corner, then loops forever.
; Assembles to the same 11 bytes as ../../cpu-emulator/roms/zero.ch8.

start:  LD   I, glyph      ; I -> sprite data
        DRW  V0, V1, 5     ; draw 5 rows at (V0, V1) = (0, 0)
done:   JP   done          ; spin here

glyph:  DB   0xF0          ; ####....
        DB   0x90          ; #..#....
        DB   0x90          ; #..#....
        DB   0x90          ; #..#....
        DB   0xF0          ; ####....
