int width(const char* s, int maxChars) {
    const int n = length(s, maxChars);
    return n == 0 ? 0 : n * kAdvance - (kAdvance - kGlyphWidth);
}

void draw(uint8_t* pixels, int w, int h, int x, int y, const char* s,
          uint8_t value, int maxChars) {
    const int n = length(s, maxChars);
    for (int i = 0; i < n; ++i) {
        const Glyph& g = find(s[i]);
        for (int row = 0; row < kGlyphHeight; ++row) {
            for (int col = 0; col < kGlyphWidth; ++col) {
                if (g.rows[row][col] != '#') {
                    continue;
                }
                const int px = x + i * kAdvance + col;
                const int py = y + row;
                if (px >= 0 && px < w && py >= 0 && py < h) {
                    pixels[py * w + px] = value;
                }
            }
        }
    }
}

void fillRect(uint8_t* pixels, int w, int h, int x, int y, int rw, int rh,
              uint8_t value) {
    for (int py = y; py < y + rh; ++py) {
        for (int px = x; px < x + rw; ++px) {
            if (px >= 0 && px < w && py >= 0 && py < h) {
                pixels[py * w + px] = value;
            }
        }
    }
}

