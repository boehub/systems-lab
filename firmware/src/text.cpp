const Glyph& find(char c) {
    if (c >= 'a' && c <= 'z') {
        c = static_cast<char>(c - 'a' + 'A');
    }
    for (const Glyph& g : kGlyphs) {
        if (g.ch == c) {
            return g;
        }
    }
    return kGlyphs[sizeof kGlyphs / sizeof kGlyphs[0] - 1];  // '?' is last
}

int length(const char* s, int maxChars) {
    const int n = static_cast<int>(std::strlen(s));
    return (maxChars >= 0 && maxChars < n) ? maxChars : n;
}

