#!/usr/bin/env python3
"""Turn programs into the C++ table the firmware menu shows.

    make_roms.py -o roms.h move.asm fib.nib game.ch8 ...

Each argument is assembly (.asm), a Nibble program (.nib) or a ready-made ROM
(.ch8). The menu name is the file name in capitals (fib.nib -> FIB). The
header defines `kRoms[]` and `kRomCount`; see src/rom_entry.h.
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
COMPILER = os.path.join(os.path.dirname(os.path.dirname(HERE)), "compiler")
sys.path.insert(0, COMPILER)

from chip8asm import AsmError, assemble  # noqa: E402
from nibble import NibbleError, compile_to_rom  # noqa: E402

MAX_ROM = 4096 - 0x200
MAX_NAME = 19  # what fits on the menu line


def menu_name(path):
    stem = os.path.splitext(os.path.basename(path))[0].upper()
    return re.sub(r"[^A-Z0-9_\-.]", "-", stem)[:MAX_NAME]


def build_rom(path):
    ext = os.path.splitext(path)[1].lower()
    with open(path, "rb") as f:
        raw = f.read()
    if ext == ".ch8":
        return raw
    text = raw.decode("utf-8")
    try:
        if ext == ".asm":
            return assemble(text)
        if ext == ".nib":
            return compile_to_rom(text)
    except (AsmError, NibbleError) as e:
        raise SystemExit(f"{path}: {e}")
    raise SystemExit(f"{path}: don't know how to build a '{ext}' file (use .asm, .nib or .ch8)")


def render(entries):
    out = ["// Generated by firmware/tools/make_roms.py. Do not edit.", "#pragma once", "",
           '#include "rom_entry.h"', ""]
    for i, (name, rom) in enumerate(entries):
        rows = [", ".join(f"0x{b:02X}" for b in rom[j:j + 12]) for j in range(0, len(rom), 12)]
        body = ",\n    ".join(rows)
        out.append(f"static const uint8_t kRomData{i}[] = {{\n    {body}\n}};")
    out.append("")
    out.append("static const RomEntry kRoms[] = {")
    for i, (name, rom) in enumerate(entries):
        out.append(f'    {{"{name}", kRomData{i}, {len(rom)}}},')
    out.append("};")
    out.append(f"static const int kRomCount = {len(entries)};")
    out.append("")
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("sources", nargs="+", help=".asm, .nib or .ch8 programs, in menu order")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args(argv)

    entries, seen = [], {}
    for path in args.sources:
        rom = build_rom(path)
        if not rom:
            raise SystemExit(f"{path}: the program is empty")
        if len(rom) > MAX_ROM:
            raise SystemExit(f"{path}: {len(rom)} bytes is too big (CHIP-8 programs get {MAX_ROM})")
        name = menu_name(path)
        seen[name] = seen.get(name, 0) + 1
        if seen[name] > 1:  # keep names unique: FIB, FIB-2, ...
            name = f"{name[:MAX_NAME - 2]}-{seen[name]}"
        entries.append((name, rom))

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(render(entries))
    print(f"{len(entries)} program(s) -> {args.output}: " + ", ".join(n for n, _ in entries))
    return 0


if __name__ == "__main__":
    sys.exit(main())
